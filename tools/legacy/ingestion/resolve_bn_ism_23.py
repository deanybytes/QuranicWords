    cit = ws.cell(r, 10).value
    t_ar = ws.cell(r, 11).value
    key = (cit, t_ar)
    if key in MAPPING_23:
        tar_bn, phrase, full_v = MAPPING_23[key]
        ws.cell(r, 13).value = tar_bn
        if full_v:
            ws.cell(r, 14).value = full_v
            updated += 1
        else:
            v_bn = str(ws.cell(r, 14).value or '')
            clean_v = re.sub(r'\(\[([^\]]+)\]\)', r'\1', v_bn)
            if phrase in clean_v:
                ws.cell(r, 14).value = clean_v.replace(phrase, f'([{phrase}])', 1)
                updated += 1

