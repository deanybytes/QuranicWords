updated = 0
unmatched = []

for r in range(2, ws.max_row + 1):
    cit = ws.cell(r, 10).value
    tar_ar = ws.cell(r, 11).value
    key = (cit, tar_ar)
    if key in FIL_UR_MAP:
        phrase = FIL_UR_MAP[key]
        ws.cell(r, 13).value = phrase
        v_ur = str(ws.cell(r, 14).value or '')
        clean_v = re.sub(r'\(\[([^\]]+)\]\)', r'\1', v_ur)
        if phrase in clean_v:
            ws.cell(r, 14).value = clean_v.replace(phrase, f'([{phrase}])', 1)
            updated += 1
        else:
            unmatched.append((r, cit, tar_ar, phrase, clean_v[:60]))
    else:
        unmatched.append((r, cit, tar_ar, 'KEY_NOT_IN_MAP', ''))

print(f'Applied Fil Urdu rules to {updated} / {ws.max_row - 1} rows.')
if unmatched:
    print(f'Unmatched rows: {len(unmatched)}')
    for u in unmatched[:10]:
        print(' ', u)

