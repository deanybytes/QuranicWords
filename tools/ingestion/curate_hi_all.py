wb = openpyxl.load_workbook('db/qw_hi.xlsx')

def apply_sheet(sname, overrides, pairs_dict):
    ws = wb[sname]
    updated = 0
    failed = []
    for r in range(2, ws.max_row + 1):
        cit = ws.cell(r, 10).value
        tar_ar = ws.cell(r, 11).value
        key = (cit, tar_ar)
        phrase = None
        
        if key in overrides:
            phrase = overrides[key]
        else:
            dict_key = f'{cit} ||| {tar_ar}'
            p = pairs_dict.get(dict_key, {})
            wbw_tr = p.get('wbw_tr', '').strip()
            v_hi = str(ws.cell(r, 14).value or '')
            clean_v = re.sub(r'\(\[([^\]]+)\]\)', r'\1', v_hi)
            tokens = [t for t in wbw_tr.split() if t not in STOP_WORDS_HI]
            if wbw_tr and wbw_tr in clean_v and wbw_tr not in STOP_WORDS_HI:
                phrase = wbw_tr
            elif len(tokens) >= 2 and ' '.join(tokens) in clean_v:
                phrase = ' '.join(tokens)
            else:
                for t in tokens:
                    if t in clean_v and len(t) > 1:
                        phrase = t
                        break
        
        if phrase:
            v_hi = str(ws.cell(r, 14).value or '')
            clean_v = re.sub(r'\(\[([^\]]+)\]\)', r'\1', v_hi)
            if phrase in clean_v:
                ws.cell(r, 13).value = phrase
                ws.cell(r, 14).value = clean_v.replace(phrase, f'([{phrase}])', 1)
                updated += 1
            else:
                failed.append((r, cit, tar_ar, phrase, clean_v[:50]))
        else:
            failed.append((r, cit, tar_ar, 'NO_PHRASE', ''))
    
    print(f'{sname}: updated {updated} / {ws.max_row - 1} rows.')
    if failed:
        print(f'{sname}: failed rows: {len(failed)}')
        for f in failed[:10]:
            print('  ', f)

