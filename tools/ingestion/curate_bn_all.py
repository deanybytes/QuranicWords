    row_num = idx + 2
    ws_ism.cell(row_num, 1).value = r_data['Rank']
    ws_ism.cell(row_num, 2).value = r_data['Arabic Lemma']
    ws_ism.cell(row_num, 3).value = r_data['Transliteration']
    ws_ism.cell(row_num, 4).value = r_data['Root']
    ws_ism.cell(row_num, 5).value = r_data['POS']
    ws_ism.cell(row_num, 6).value = r_data['Occurrences']
    ws_ism.cell(row_num, 7).value = r_data['Coverage %']
    ws_ism.cell(row_num, 8).value = r_data['Sense Index']
    ws_ism.cell(row_num, 10).value = r_data['Verse Citation']
    ws_ism.cell(row_num, 11).value = r_data['Target Arabic Word']
    ws_ism.cell(row_num, 12).value = r_data['Full Arabic Verse']
    
    cit = r_data['Verse Citation']
    t_ar = r_data['Target Arabic Word']
    key = (cit, t_ar)
    
    if key in BN_ISM_RULES:
        tar_bn, phrase = BN_ISM_RULES[key]
        ws_ism.cell(row_num, 13).value = tar_bn
        v_bn = str(ws_ism.cell(row_num, 14).value or '')
        clean_v = re.sub(r'\(\[([^\]]+)\]\)', r'\1', v_bn)
        raw_phrase = phrase.replace('([', '').replace('])', '')
        if raw_phrase in clean_v:
            ws_ism.cell(row_num, 14).value = clean_v.replace(raw_phrase, phrase, 1)
        elif tar_bn in clean_v:
            ws_ism.cell(row_num, 14).value = clean_v.replace(tar_bn, f'([{tar_bn}])', 1)
    else:
        t_bn = str(ws_ism.cell(row_num, 13).value or '').strip()
        v_bn = str(ws_ism.cell(row_num, 14).value or '')
        if f'([{t_bn}])' not in v_bn and t_bn in v_bn:
            ws_ism.cell(row_num, 14).value = v_bn.replace(t_bn, f'([{t_bn}])', 1)

